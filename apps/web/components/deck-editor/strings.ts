export const DECK_STRINGS = { fr, en };

export type DeckLocale = "fr" | "en";

export function deckString(locale: DeckLocale, key: DeckStringKey, vars?: Record<string, string | number>): string {
  let text = (locale === "en" ? en : fr)[key] ?? fr[key] ?? key;
  if (vars) for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, String(value));
  return text;
}

export type DeckT = (key: DeckStringKey, vars?: Record<string, string | number>) => string;

export function useDeckStrings(): { t: DeckT; locale: DeckLocale } {
  const { locale } = useI18n();
  const lang: DeckLocale = locale === "en" ? "en" : "fr";
  const t = useCallback<DeckT>((key, vars) => deckString(lang, key, vars), [lang]);
  return { t, locale: lang };
}

