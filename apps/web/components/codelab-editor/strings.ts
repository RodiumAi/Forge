export type Translate = (key: CodelabEditorKey, vars?: Record<string, string | number>) => string;

export function editorTranslator(locale: string): Translate {
  const table: Record<CodelabEditorKey, string> = locale === "en" ? en : fr;
  return (key, vars) => {
    let text = table[key] ?? fr[key] ?? key;
    for (const [name, value] of Object.entries(vars ?? {})) text = text.replaceAll(`{${name}}`, String(value));
    return text;
  };
}

export function useCodelabStrings(): { t: Translate; locale: "fr" | "en" } {
  const { locale } = useI18n();
  const lang = locale === "en" ? "en" : "fr";
  const t = useCallback<Translate>((key, vars) => editorTranslator(lang)(key, vars), [lang]);
  return { t, locale: lang };
}
