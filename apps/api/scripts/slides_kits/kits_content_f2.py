"""Content of the wave 2 (agent F2) slides kits: 15 French example decks.

Each kit adds a ``style`` dict read by kitstyle_f2.make_post (header, pattern,
cover, image treatment, figures, quote, avatars, closing). Build with
``python build_kits.py <repo> <images> kits_content_f2 [ids...]``.
"""
from kitlib import shape
from kitstyle_f2 import make_post

KITS = []

ROLE_ORDER = ("bg", "surface", "fg", "muted", "accent", "accent-2", "border")


def palette(spec, contrast):
    colors = dict(zip(ROLE_ORDER, spec.split(" / "), strict=True))
    colors["accent-contrast"] = contrast
    # Keep the charter order of build_kits (accent-contrast before border).
    order = ("bg", "surface", "fg", "muted", "accent", "accent-2", "accent-contrast", "border")
    return {k: colors[k] for k in order}


def kit(*, kid, category, title, description, boot, tags, tone, deck_title, theme, images, style, slides):
    theme = dict(theme)
    theme["colors"] = palette(theme.pop("palette"), theme.pop("contrast"))
    KITS.append({
        "id": kid, "category": category, "title": title, "description": description,
        "bootHint": boot, "tags": tags, "tone": tone, "deck_title": deck_title,
        "theme": theme, "images": images, "slides": slides, "post": make_post(style),
    })


def people(*rows):
    return [{"name": n, "role": r, "bio": b} for n, r, b in rows]


def steps(*rows):
    return [{"date": d, "title": t, "desc": x} for d, t, x in rows]


def figs(*rows):
    return [{"value": v, "label": label, "detail": d} for v, label, d in rows]


